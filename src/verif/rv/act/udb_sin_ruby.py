# udb_sin_ruby.py — Lo que ACT4 le pide a UDB, sin Ruby ni rubygems.org
#
# riscv-arch-test (ACT4) usa tres órdenes de las gemas de riscv-unified-db,
# siempre a través de `bundle exec`:
#
#   udb validate cfg <cfg.yaml>
#   udb list extensions --config <cfg.yaml> --output <extensions.txt>
#   udb-gen cfg-c-header|cfg-svh-header -c <cfg.yaml> -o <salida>
#
# Con una configuración «fully configured» las tres son mecánicas: la lista de
# extensiones es la del YAML, y las cabeceras son un #define por extensión y
# por parámetro. Este programa las reproduce tal cual las escribe udb-gen
# 0.1.17 (lib/udb-gen/cfg_header_base.rb y generators/cfg_*_header), para
# poder generar las pruebas donde no se llega a rubygems.org.
#
# `validate` solo comprueba que el YAML se lee y es «fully configured»: NO
# valida los parámetros contra el esquema de UDB. Si se puede, hay que pasar
# la configuración una vez por el udb de verdad (`bundle exec udb validate cfg`).
#
# El envoltorio `bin/bundle` hace de `bundle`: pon act/bin en el PATH.
# =============================================================================
import re
import sys
from pathlib import Path

try:
    import yaml

    def lee_yaml(texto):
        return yaml.safe_load(texto)
except ImportError:  # el entorno de uv de ACT trae ruamel.yaml
    from ruamel.yaml import YAML

    def lee_yaml(texto):
        return YAML(typ="safe", pure=True).load(texto)


def carga(ruta):
    cfg = lee_yaml(Path(ruta).read_text())
    if cfg.get("type") != "fully configured":
        sys.exit(f"{ruta}: solo se admiten configuraciones «fully configured»")
    return cfg


def rvi(version):
    # «= 2.1» -> 2p1, «= 1.12.0» -> 1p12p0 (VersionSpec#to_rvi_s)
    v = str(version).strip().lstrip("=~>< ").strip()
    pre = v.endswith("-pre")
    if pre:
        v = v[: -len("-pre")]
    s = "p".join(str(int(x)) for x in v.split("."))
    return s + ("-pre" if pre else "")


def identificador(s):
    s = re.sub(r"[^A-Z0-9]", "_", s.upper())
    s = re.sub(r"_+", "_", s)
    return s.strip("_")


def cabecera(cfg, svh):
    d = "`define" if svh else "#define"
    nombre = cfg["name"]
    guarda = "UDB_CFG_" + re.sub(r"[^A-Z0-9]", "_", nombre.upper()) + ("_SVH" if svh else "_H")
    orden = "cfg-svh-header" if svh else "cfg-c-header"

    def entero(v):
        if svh:
            bits = max(32, v.bit_length())
            return f"{((bits + 31) // 32) * 32}'h{v:X}"
        return f"{v}ULL" if v.bit_length() > 63 else str(v)

    def mascara(v):
        return entero(v) if svh else f"0x{v:X}"

    conv = [
        "SPDX-License-Identifier: BSD-3-Clause-Clear",
        "",
        f"Auto-generated by riscv-unified-db (udb-gen {orden})",
        f"Config: {nombre}",
        "",
        "Define conventions:",
        f"  Extensions:           {d} NAME_SUPPORTED and {d} NAMEverPver_SUPPORTED",
        f"  Boolean params:       {d} UDB_NAME           (present when true, absent when false)",
        f"  Integer params:       {d} UDB_NAME value     and {d} UDB_NAME_<value>",
        f"  Enum (string) params: {d} UDB_NAME_VALUE     (value sanitized to uppercase identifier)",
        f"  Boolean arrays:       {d} UDB_NAME_<index>   (one per true element)",
        f"                        {d} UDB_NAME_MASK      (bit <index> set when element <index> is true)",
        f"  Integer arrays:       {d} UDB_NAME_<value>   (one per unique element, sorted)",
        f"  String arrays:        {d} UDB_NAME_<VALUE>   (one per unique element, sanitized)",
    ]
    if svh:
        l = ["//" if not x else f"// {x}" for x in conv]
    else:
        l = ["/*"] + [" *" if not x else f" * {x}" for x in conv] + [" */"]
    com = (lambda t: f"// {t}") if svh else (lambda t: f"/* {t} */")
    l += ["", f"`ifndef {guarda}" if svh else f"#ifndef {guarda}", f"{d} {guarda}", "", com("Implemented extensions")]
    for e in sorted(cfg["implemented_extensions"], key=lambda e: e["name"].upper()):
        n = e["name"].upper()
        l.append(f"{d} {n}_SUPPORTED")
        l.append(f"{d} {n}{rvi(e['version']).upper()}_SUPPORTED")
    l += ["", com("Configuration parameters")]
    for k, v in sorted((cfg.get("params") or {}).items()):
        p = f"UDB_{k}"
        if v is True:
            l.append(f"{d} {p}")
        elif v is False:
            continue
        elif isinstance(v, int):
            l.append(f"{d} {p} {entero(v)}")
            l.append(f"{d} {p}_{v}")
        elif isinstance(v, str):
            l.append(f"{d} {p}_{identificador(v)}")
        elif isinstance(v, list) and v:
            if all(isinstance(x, bool) for x in v):
                l += [f"{d} {p}_{i}" for i, x in enumerate(v) if x]
                l.append(f"{d} {p}_MASK {mascara(sum(1 << i for i, x in enumerate(v) if x))}")
            elif all(isinstance(x, int) and not isinstance(x, bool) for x in v):
                l += [f"{d} {p}_{x}" for x in sorted(set(v))]
            elif all(isinstance(x, str) for x in v):
                l += [f"{d} {p}_{x}" for x in sorted({identificador(s) for s in v})]
    l += ["", f"`endif // {guarda}" if svh else f"#endif /* {guarda} */", ""]
    return "\n".join(l)


def opcion(args, *nombres):
    for i, a in enumerate(args):
        for n in nombres:
            if a == n and i + 1 < len(args):
                return args[i + 1]
            if a.startswith(n + "="):
                return a.split("=", 1)[1]
    return None


def escribe(salida, texto):
    if salida in (None, "-"):
        sys.stdout.write(texto)
    else:
        Path(salida).parent.mkdir(parents=True, exist_ok=True)
        Path(salida).write_text(texto)


def main(a):
    if a[:2] == ["udb", "validate"] and len(a) >= 4:
        carga(a[3])
        print(f"{a[3]}: fully configured (comprobación reducida de udb_sin_ruby.py)")
        return 0
    if a[:3] == ["udb", "list", "extensions"]:
        cfg = carga(opcion(a, "--config"))
        escribe(opcion(a, "--output", "-o"), "".join(e["name"] + "\n" for e in cfg["implemented_extensions"]))
        return 0
    if a[:1] == ["udb-gen"] and len(a) >= 2 and a[1] in ("cfg-c-header", "cfg-svh-header"):
        cfg = carga(opcion(a, "-c", "--config"))
        escribe(opcion(a, "-o", "--output"), cabecera(cfg, a[1] == "cfg-svh-header"))
        return 0
    sys.exit("udb_sin_ruby.py: orden no soportada: " + " ".join(a))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
